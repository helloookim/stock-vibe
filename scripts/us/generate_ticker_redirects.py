"""
US 티커 변경 리다이렉트 맵 생성 → src/usTickerRedirects.js

prepare_us_data.py 로 인덱스를 덮어쓰기 **전에** 실행해야 한다 (현재 public 인덱스 = 옛 티커).

규칙: 현재 인덱스에 있던 티커 T 가 새 인덱스에서 빠졌고, T 의 CIK 가 새 인덱스의
다른 티커 T' 로 이어지면 T → T' (예: GOOG → GOOGL, PSTG → P, GME-WT → GME).
CIK 가 아예 사라진 종목(인수/상장폐지)은 리다이렉트하지 않는다.

기존 맵은 누적 유지하되, 소스가 다시 유효한 티커가 되면 제거하고, 대상이 또 바뀌면 체인을 따라간다.
사용처: functions/[[path]].js (301), src/pages/UsStockPage.jsx (클라이언트 replace)
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from config import REPO_ROOT, FIXED_DIR, TICKER_FILE, PUBLIC_US_DIR, PUBLIC_US_INDEX, CIK_ALIAS_FILE  # noqa: E402

OUT_JS = REPO_ROOT / "src" / "usTickerRedirects.js"
WINDOWS_RESERVED_NAMES = re.compile(r'^(CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])$', re.IGNORECASE)


def _cik(path):
    try:
        with open(path, encoding="utf-8") as f:
            return int(json.load(f)["cik"])
    except Exception:
        return None


def load_existing():
    if not OUT_JS.exists():
        return {}
    m = re.search(r"=\s*(\{.*\});", OUT_JS.read_text(encoding="utf-8"), re.S)
    return json.loads(m.group(1)) if m else {}


def main():
    with open(PUBLIC_US_INDEX, encoding="utf-8") as f:
        old_index = {e["ticker"] for e in json.load(f)}

    with open(TICKER_FILE, encoding="utf-8") as f:
        tickers_raw = json.load(f)
    available = {p.stem for p in FIXED_DIR.glob("*.json")}
    new_index = {e["ticker"] for e in tickers_raw.values()
                 if e["ticker"] in available and not WINDOWS_RESERVED_NAMES.match(e["ticker"])}

    # 새 인덱스: CIK → 티커 (병합된 옛 CIK 별칭 포함)
    cik_to_new = {}
    for t in new_index:
        c = _cik(FIXED_DIR / f"{t}.json")
        if c is not None:
            cik_to_new[c] = t
    if CIK_ALIAS_FILE.exists():
        for old_cik, info in json.loads(CIK_ALIAS_FILE.read_text(encoding="utf-8")).items():
            if info.get("merge") is True and info["ticker"] in new_index:
                cik_to_new.setdefault(int(old_cik), info["ticker"])
                cik_to_new.setdefault(int(info["new_cik"]), info["ticker"])

    redirects = load_existing()
    added = 0
    for t in sorted(old_index - new_index):
        c = _cik(PUBLIC_US_DIR / f"{t}.json")
        target = cik_to_new.get(c)
        if target and target != t:
            redirects[t] = target
            added += 1

    # 정리: 소스가 다시 유효해졌으면 제거, 대상 체인 해소, 대상이 사라졌으면 제거
    for src in list(redirects):
        if src in new_index:
            del redirects[src]
    for src in list(redirects):
        seen, dst = {src}, redirects[src]
        while dst in redirects and dst not in seen:
            seen.add(dst)
            dst = redirects[dst]
        if dst in new_index:
            redirects[src] = dst
        else:
            del redirects[src]

    body = json.dumps(dict(sorted(redirects.items())), indent=0, ensure_ascii=False)
    OUT_JS.write_text(
        "// AUTO-GENERATED by scripts/us/generate_ticker_redirects.py — do not edit by hand.\n"
        "// Old US ticker → current ticker (ticker changes / primary-share remaps). Used by\n"
        "// functions/[[path]].js (301) and src/pages/UsStockPage.jsx (client-side replace).\n"
        f"export const US_TICKER_REDIRECTS = {body};\n",
        encoding="utf-8",
    )
    print(f"리다이렉트 이번 신규 {added}개, 전체 {len(redirects)}개 → {OUT_JS}")


if __name__ == "__main__":
    main()
